-- Prologue Society scan app: initial schema.
-- The app talks to Postgres server-side only (DATABASE_URL). Row level security is
-- switched on for every table with no policies, so Supabase's public REST API
-- (anon key) can read and write nothing.

create schema if not exists extensions;
create extension if not exists pg_trgm with schema extensions;
-- gen_random_uuid() is built in from Postgres 13

-- ---------------------------------------------------------------- members
create table members (
  id                         uuid primary key default gen_random_uuid(),
  member_number              integer generated by default as identity unique,
  first_name                 text not null default '',
  last_name                  text not null default '',
  full_name                  text generated always as (btrim(first_name || ' ' || last_name)) stored,
  email                      text,
  phone                      text,
  date_of_birth              date,
  tier                       text not null default 'Standard' check (tier in ('Founding', 'Standard')),
  billing                    text check (billing in ('Annual', 'Monthly')),
  -- Raw Chargebee subscription status: active, in_trial, non_renewing, paused, cancelled, future
  subscription_status        text,
  -- Set when a payment fails; benefits stay on (amber "Grace") until this passes or payment succeeds
  payment_failed_at          timestamptz,
  grace_until                timestamptz,
  cancelled_at               timestamptz,
  join_date                  date,
  next_renewal               date,
  chargebee_customer_id      text unique,
  chargebee_subscription_id  text,
  chargebee_plan             text,
  photo_url                  text,
  -- Reading preferences (Typeform)
  genres_loved               text[] not null default '{}',
  genres_avoid               text[] not null default '{}',
  favourite_books            text,
  favourite_authors          text,
  reading_now                text,
  books_per_month            text,
  reading_notes              text,
  preferences_submitted      date,
  -- Admin
  marketing_consent          boolean not null default false,
  founders_board_name        text,
  welcome_pack_sent          boolean not null default false,
  card_issued                boolean not null default false,
  airtable_record_id         text unique,
  created_at                 timestamptz not null default now(),
  updated_at                 timestamptz not null default now()
);
create unique index members_email_key on members (lower(email)) where email is not null;
create index members_name_trgm on members using gin (full_name extensions.gin_trgm_ops);
create index members_email_trgm on members using gin (lower(email) extensions.gin_trgm_ops);

-- ---------------------------------------------------------------- tokens
-- What the QR holds. Opaque, e.g. PS-7F3K9Q2M. A lost card: revoke and issue a new one.
create table member_tokens (
  token          text primary key check (token ~ '^PS-[0-9A-Z]{8}$'),
  member_id      uuid not null references members (id) on delete cascade,
  kind           text not null default 'card' check (kind in ('card', 'wallet')),
  issued_at      timestamptz not null default now(),
  revoked_at     timestamptz,
  revoked_reason text
);
create index member_tokens_member on member_tokens (member_id);

-- ---------------------------------------------------------------- staff
create table staff (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  email       text,
  role        text not null default 'staff' check (role in ('staff', 'manager')),
  pin_hash    text not null,           -- scrypt, see lib/pin.ts
  failed_pins integer not null default 0,
  locked_until timestamptz,            -- 5 wrong PINs locks that person for 5 minutes
  active      boolean not null default true,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------- benefits
create table benefits (
  key                  text primary key,
  name                 text not null,
  short_name           text not null,
  description          text,
  -- How often it can be used. Redeemable benefits allow one use per period.
  allowance            text not null check (allowance in
                         ('calendar_month', 'calendar_quarter', 'membership_year', 'membership', 'per_event', 'unlimited')),
  redeemable           boolean not null default false,
  birthday_month_only  boolean not null default false,
  tiers                text[] not null default '{Founding,Standard}',
  sort                 integer not null default 100,
  active               boolean not null default true
);

-- ---------------------------------------------------------------- events
create table events (
  id            uuid primary key default gen_random_uuid(),
  name          text not null,
  starts_at     timestamptz not null,
  ends_at       timestamptz,
  society_only  boolean not null default true,
  -- true: every active member may come; false: only members on event_guests
  open_to_all   boolean not null default true,
  created_at    timestamptz not null default now()
);
create index events_starts on events (starts_at);

create table event_guests (
  event_id   uuid not null references events (id) on delete cascade,
  member_id  uuid not null references members (id) on delete cascade,
  added_at   timestamptz not null default now(),
  primary key (event_id, member_id)
);

-- ---------------------------------------------------------------- redemptions
create table redemptions (
  id           uuid primary key default gen_random_uuid(),
  member_id    uuid not null references members (id) on delete cascade,
  benefit_key  text not null references benefits (key),
  -- Which allowance window this use counts against, e.g. m:2026-11, y:2026-03-14, e:<event uuid>
  period_key   text not null,
  event_id     uuid references events (id),
  station      text not null,
  staff_id     uuid references staff (id) on delete set null,
  redeemed_at  timestamptz not null default now(),
  details      text,
  -- Set by the device; makes queued offline redemptions safe to retry
  client_id    uuid unique,
  offline      boolean not null default false,
  undone_at    timestamptz,
  undone_by    uuid references staff (id) on delete set null,
  undo_reason  text
);
-- The rule that stops a drink being poured twice, even from two tills at once.
create unique index redemptions_one_per_period
  on redemptions (member_id, benefit_key, period_key) where undone_at is null;
create index redemptions_member on redemptions (member_id, redeemed_at desc);
create index redemptions_time on redemptions (redeemed_at desc);

-- ---------------------------------------------------------------- notes
create table member_notes (
  id          uuid primary key default gen_random_uuid(),
  member_id   uuid not null references members (id) on delete cascade,
  staff_id    uuid references staff (id) on delete set null,
  body        text not null check (length(body) between 1 and 2000),
  created_at  timestamptz not null default now(),
  deleted_at  timestamptz
);
create index member_notes_member on member_notes (member_id, created_at desc);

-- ---------------------------------------------------------------- scans
-- Kept 12 months (GDPR data minimisation); /api/cron/retention deletes older rows daily.
create table scans (
  id          uuid primary key default gen_random_uuid(),
  scanned_at  timestamptz not null default now(),
  token       text,
  member_id   uuid references members (id) on delete set null,
  result      text not null check (result in ('active', 'grace', 'lapsed', 'unrecognised', 'lookup')),
  station     text not null,
  mode        text not null default 'staff' check (mode in ('staff', 'concierge', 'welcome', 'kiosk')),
  staff_id    uuid references staff (id) on delete set null,
  device_id   text
);
create index scans_time on scans (scanned_at desc);
create index scans_member on scans (member_id, scanned_at desc);

-- ---------------------------------------------------------------- stations
-- Pairs a concierge staff tablet with its customer-facing welcome screen.
create table stations (
  code              text primary key check (code ~ '^[A-Z0-9]{4,8}$'),
  name              text not null,
  staff_seen_at     timestamptz,           -- heartbeat from the staff concierge view
  display_seen_at   timestamptz,           -- heartbeat from the welcome screen
  current_member_id uuid references members (id) on delete set null,
  current_payload   jsonb,                 -- what the welcome screen should show (no PII beyond first name)
  current_scan      jsonb,                 -- what the staff concierge view should open: {token, memberId, revokedAt}
  current_seq       bigint not null default 0,
  current_at        timestamptz
);

-- ---------------------------------------------------------------- housekeeping
create or replace function touch_updated_at() returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end $$;
create trigger members_touch before update on members for each row execute function touch_updated_at();

alter table members        enable row level security;
alter table member_tokens  enable row level security;
alter table staff          enable row level security;
alter table benefits       enable row level security;
alter table events         enable row level security;
alter table event_guests   enable row level security;
alter table redemptions    enable row level security;
alter table member_notes   enable row level security;
alter table scans          enable row level security;
alter table stations       enable row level security;

